export function setLang(lang: Lang) { currentLang = lang; localStorage.setItem('lang', lang); window.dispatchEvent(new CustomEvent('langchange', { detail: lang })); }
export function getLang(): Lang { return currentLang; }
export function t(key: string): string { const dict = translations[currentLang as keyof typeof translations] as Record<string, string>; return dict?.[key] || (translations as any).en?.[key] || key; }
import { useState, useEffect, useCallback } from 'react';
export function useTranslation() { const [lang, setLangState] = useState<Lang>(currentLang); useEffect(() => { const handler = () => setLangState(currentLang); window.addEventListener('langchange', handler); return () => window.removeEventListener('langchange', handler); }, []); const changeLang = useCallback((newLang: Lang) => { setLangState(newLang); setLang(newLang); }, []); return { t, lang, setLang: changeLang }; }
